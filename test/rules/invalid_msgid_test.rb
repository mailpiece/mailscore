require "test_helper"

class MailScore::Rules::InvalidMsgidTest < MailScore::TestCase
  def test_an_id_without_a_domain_or_with_spaces
    assert_equal "<1234>", run_rule("<1234>").detail
    assert_equal 1.7, run_rule("<1234>").weight
    assert run_rule("<1@example.com> <2@example.com>")
    assert run_rule("<1@exämple.com>")
    assert run_rule("")
  end

  def test_brackets_are_optional_and_a_comment_passes
    assert_nil run_rule("1234@example.com")
    assert_nil run_rule("<a@b@c>")
    assert_nil run_rule("<1234> (generated by a broken mailer)")
  end

  def test_a_well_formed_or_missing_id
    assert_nil run_rule("<CAF=x+y.1@mail.example.com>")
    assert_nil run_rule(nil)
  end

  def test_one_well_formed_id_among_several_passes
    message = MailScore::Message.new("Message-ID: <1234>\nMessage-ID: <1@example.com>\nSubject: hi\n\nbody")

    assert_nil MailScore::Rules::InvalidMsgid.new(nil, nil).run(message, MailScore::Envelope.read({}, message))
  end

  private
    def run_rule(id)
      message = MailScore::Message.new("#{"Message-ID: #{id}\n" if id}Subject: hi\n\nbody")
      MailScore::Rules::InvalidMsgid.new(nil, nil).run(message, MailScore::Envelope.read({}, message))
    end
end
